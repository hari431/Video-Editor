-- 003: permanent administrator accounts
--
-- Administrators (ADMIN_EMAILS) are permanent: status = 'active' and
-- access_expires_at = NULL. Pending users are also created with
-- access_expires_at = NULL. The original schema declared the column
-- NOT NULL, which prevents both from being stored, so the constraint
-- must be relaxed.
--
-- Normal users still receive an explicit expiry via admin approval/extension;
-- the application and middleware continue to require an unexpired
-- access_expires_at for non-admin access.
ALTER TABLE users ALTER COLUMN access_expires_at DROP NOT NULL;