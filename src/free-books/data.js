export const FREE_TECHNICAL_BOOK_CATEGORIES = [...new Set(FREE_TECHNICAL_BOOKS.map(item => item.category))].sort();

export function getFreeTechnicalBooks({ category = '', kind = '' } = {}) {
  const c = String(category || '').trim().toLowerCase();
  const k = String(kind || '').trim().toLowerCase();
  return FREE_TECHNICAL_BOOKS.filter(item =>
    (!c || item.category.toLowerCase() === c) &&
    (!k || item.kind === k)
  );
}
